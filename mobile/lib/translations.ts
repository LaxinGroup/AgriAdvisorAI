export const translations: Record<SupportedLocale, Translations> = { en, afr, es, fr };

export function translate(
  language: SupportedLocale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const text = translations[language][key] ?? en[key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

// An error whose message comes from this list, so screens can show it in the chosen language.
export class TranslatableError extends Error {
  constructor(
    readonly key: TranslationKey,
    readonly params?: Record<string, string | number>,
  ) {
    super(translate('en', key, params));
    this.name = 'TranslatableError';
  }
}
